"""Honest test: compare the human labels in labels.csv with both models and a word list.

Run (from the eval/ folder):  ../.venv/bin/python evaluate.py
Writes:
  test_table.csv  every item with the human label and all three outputs
  RESULTS.md      agreement, confusion matrices, per-group scores, all disagreements
"""

import re
import sys
from pathlib import Path

import pandas as pd
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))
import config  # noqa: E402

LABELS = ["negative", "neutral", "positive"]

# A deliberately simple Dutch word list: the "no AI" baseline.
# Only general sentiment words. Words that appear only in our 50 test items were left out
# on purpose, otherwise the baseline would be tuned to the test (see README).
POS = ["goed", "blij", "mooi", "prima", "gratis", "goedkoop", "goedkoper", "voordeel", "besparen",
       "bespaar", "slim", "oplossing", "oplossen", "beter", "top", "fijn", "succes", "handig",
       "positief", "tevreden", "geweldig", "super", "aanrader", "winst"]
NEG = ["probleem", "problemen", "duur", "duurder", "slecht", "crisis", "stop", "vertraagd",
       "vertraging", "verlies", "verliezen", "boete", "bizar", "overlast", "klacht", "klachten",
       "negatief", "chaos", "onzin", "schandalig", "teleurgesteld", "storing", "zorgen", "boos"]


def wordlist(text):
    t = text.lower()
    score = sum(len(re.findall(rf"\b{re.escape(w)}", t)) for w in POS) \
        - sum(len(re.findall(rf"\b{re.escape(w)}", t)) for w in NEG)
    return "positive" if score > 0 else "negative" if score < 0 else "neutral"


def cm_table(y_true, y_pred, labels):
    cm = confusion_matrix(y_true, y_pred, labels=labels)
    head = "| human ↓ / model → | " + " | ".join(labels) + " |\n|---|" + "---|" * len(labels) + "\n"
    return head + "\n".join(f"| **{l}** | " + " | ".join(str(v) for v in row) + " |" for l, row in zip(labels, cm))


def pct(x):
    return f"{100 * x:.0f}%"


def main():
    lab = pd.read_csv(HERE / "labels.csv", dtype=str)
    items = pd.read_csv(config.ITEMS_CSV)[["id", "main_label", "main_mood", "cmp_label", "cmp_mood"]]
    df = lab.merge(items, on="id", how="left")
    df["wordlist"] = df["text"].map(wordlist)
    df = df.rename(columns={"main_label": "xlmr", "cmp_label": "robbert"})

    models = {"XLM-RoBERTa (main)": "xlmr", "RobBERT Dutch (comparison)": "robbert", "Word list (baseline)": "wordlist"}
    y = df["label"]
    polar = y != "neutral"

    rows = []
    for name, col in models.items():
        rows.append({
            "model": name,
            "agree, all 50": pct(accuracy_score(y, df[col])),
            "macro-F1, all 50": f"{f1_score(y, df[col], labels=LABELS, average='macro', zero_division=0):.2f}",
            f"agree, {polar.sum()} non-neutral": pct(accuracy_score(y[polar], df.loc[polar, col])),
            "agree, news": pct(accuracy_score(y[df.kind == "news"], df.loc[df.kind == "news", col])),
            "agree, Bluesky": pct(accuracy_score(y[df.kind == "public"], df.loc[df.kind == "public", col])),
        })
    summary = pd.DataFrame(rows)

    per_line = pd.DataFrame({
        name: df.groupby("line").apply(lambda g, c=col: pct(accuracy_score(g["label"], g[c])), include_groups=False)
        for name, col in models.items()
    })

    # What the user actually sees is the AVERAGE mood per line, so compare that too.
    num = {"negative": -1, "neutral": 0, "positive": 1}
    line_level = pd.DataFrame({
        "human average": df.groupby("line")["label"].apply(lambda s: s.map(num).mean()),
        "XLM-R average mood": df.groupby("line")["main_mood"].mean(),
        "RobBERT average mood": df.groupby("line")["cmp_mood"].mean(),
        "word list average": df.groupby("line")["wordlist"].apply(lambda s: s.map(num).mean()),
    }).round(2)

    df["xlmr_right"] = df["xlmr"] == df["label"]
    df["robbert_right"] = df["robbert"] == df["label"]
    df["wordlist_right"] = df["wordlist"] == df["label"]
    df["models_disagree"] = df["xlmr"] != df["robbert"]
    table = df[["nr", "line", "kind", "source", "text", "label", "on_topic", "note", "xlmr", "main_mood",
                "robbert", "cmp_mood", "wordlist", "xlmr_right", "robbert_right", "wordlist_right",
                "models_disagree", "labelled_by", "checked_by_majed"]]
    table.to_csv(HERE / "test_table.csv", index=False)

    wrong = df[~df["xlmr_right"]]
    checked = (df["checked_by_majed"].fillna("").str.strip() != "").sum()
    md = [
        "# Honest test – results",
        "",
        f"_Generated by `evaluate.py`. Labels: {len(df)} items "
        f"({(y == 'negative').sum()} negative, {(y == 'neutral').sum()} neutral, {(y == 'positive').sum()} positive). "
        f"Drafted by Claude, checked by Majed: {checked}/{len(df)}._",
        "",
        "## Agreement with the human labels",
        "",
        summary.to_markdown(index=False),
        "",
        "RobBERT can only answer positive or negative, so it is **always wrong on neutral items**. "
        "The non-neutral column is its fair score.",
        "",
        "## Agreement per line",
        "",
        per_line.to_markdown(),
        "",
        "## What the user sees: average mood per line (−1 … +1)",
        "",
        line_level.to_markdown(),
        "",
        "## Confusion matrix – XLM-RoBERTa (main)",
        "",
        cm_table(y, df["xlmr"], LABELS),
        "",
        "## Confusion matrix – RobBERT Dutch (comparison)",
        "",
        cm_table(y, df["robbert"], LABELS),
        "",
        "## Confusion matrix – word list (baseline)",
        "",
        cm_table(y, df["wordlist"], LABELS),
        "",
        f"## Every item XLM-RoBERTa got wrong ({len(wrong)})",
        "",
        "| nr | line | kind | human | XLM-R | RobBERT | text | note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in wrong.itertuples():
        text = r.text.replace("|", "/")[:160]
        md.append(f"| {r.nr} | {r.line} | {r.kind} | {r.label} | {r.xlmr} | {r.robbert} | {text} | {r.note if isinstance(r.note, str) else ''} |")
    (HERE / "RESULTS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(summary.to_string(index=False))
    print()
    print(per_line)
    print()
    print(line_level)


if __name__ == "__main__":
    main()
